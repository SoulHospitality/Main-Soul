/**
 * Escape a value for use as text or a quoted attribute in an HTML email.
 * null and undefined become ''; everything else is stringified (so 0 stays "0").
 */
function escapeHtml(value) {
  if (value == null) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

module.exports = { escapeHtml };
